template <typename Bv>
BvhTree<Bv>::BvhTree(BvhObject<Bv> const* object, BvhTreeParams const& params) {
  MOCHI_PROFILE_SCOPE();
  MOCHI_ASSERT(object, "Invalid BVH object supplied");
  MOCHI_ASSERT(object->GetNumElements() > 0, "Cannot build BVH tree from empty object.");
  MOCHI_ASSERT(
      (dynamic_cast<PointSetBvhObject<Bv> const*>(object) == nullptr) ||
          (params.splittingAlgorithm != BvhSplittingAlgorithm::TopDown_AreaWeightedMean),
      "PointSetBvhObject does not support area-weighted splitting. Use BvhSplitting::AlgorithmTopDown_Mean instead.");
  _object = object;
  _params = params;

  // Preallocate node levels. Since we don't know the exact number in advance, pre-allocate
  // according to the maximum number of levels as prescribed by the parameters. We need this for
  // keeping track of what nodes constitute a depth level (so we can parallelize the fitting
  // procedure).
  _levels.resize(_params.maxDepthPerBranch);

  // Initialize element partition in no particular order. Then, start build procedure from root
  // node. NOTE@Hector: We only support top-down building as of now. If this proves to be
  // insufficient (e.g., because of the quality of the tree) then we will need to modify all this.
  _elements.resize(_object->GetNumElements());
  std::iota(_elements.begin(), _elements.end(), 0);
  BuildNode(kInvalidIndex, MakeSpan(_elements), /*depth*/ 0);

  // Once built, deallocate extra memory by shrinking buffers. This step will also remove empty
  // levels, thus making the levels vector be of the same size as the maximum depth reached.
  ShrinkBuffers();
}

template <typename Bv>
bool BvhTree<Bv>::IsValid() const {
  return _object && _object->GetNumElements() == _elements.size();
}

template <typename Bv>
BvhObject<Bv> const* BvhTree<Bv>::GetObject() const {
  return _object;
}

template <typename Bv>
BvhTreeParams const& BvhTree<Bv>::GetParams() const {
  return _params;
}

template <typename Bv>
Bv const& BvhTree<Bv>::GetRootBv() const {
  MOCHI_ASSERT_VERBOSE(IsValid(), "Invalid BVH Tree");
  return _nodes[kRootNode].bv;
}

template <typename Bv>
void BvhTree<Bv>::Refit() {
  MOCHI_PROFILE_SCOPE();
  MOCHI_ASSERT_VERBOSE(IsValid(), "Invalid BVH Tree");

  // Refit entries in parallel bottom-up.
  for (int i = isize(_levels) - 1; i >= 0; --i) {
    ParallelForEach("RefitNode", _levels[i], _params.refitGranularity, [this](auto& entry) {
      RefitNode(entry);
    });
  }
}

template <typename Bv>
void BvhTree<Bv>::Query(Bv const& bv, BvhQueryFn const& callback) const {
  MOCHI_ASSERT_VERBOSE(IsValid(), "Invalid BVH Tree");
  QueryNode(bv, kRootNode, callback);
}

template <typename Bv>
void BvhTree<Bv>::Intersect(BvhTree const& other, BvhIntersectionQueryFn const& callback) const {
  MOCHI_ASSERT_VERBOSE(IsValid(), "Invalid BVH Tree");
  MOCHI_ASSERT_VERBOSE(other.IsValid(), "Invalid BVH Tree");
  MOCHI_ASSERT_VERBOSE(&other != this, "BvhTree::Intersect does not support self-intersection.");

  IntersectNodes(other, kRootNode, kRootNode, callback);
}

template <typename Bv>
int BvhTree<Bv>::FindClosest(Real3 const& queryPoint, real* outDistanceSqr) const {
  return VFindClosest(ToSimd(queryPoint), outDistanceSqr);
}

template <typename Bv>
int BvhTree<Bv>::VFindClosest(Vec4r queryPoint, real* outDistanceSqr) const {
  MOCHI_ASSERT_VERBOSE(IsValid(), "Invalid BVH Tree");

  // Initialize candidate to arbitrary entry.
  int bestIndex = 0;
  real bestDistanceSqr = Get0(_object->VGetDistanceSqr(queryPoint, 0));

  // Traverse tree.
  FindClosestOnNode(kRootNode, queryPoint, bestIndex, bestDistanceSqr);

  // Finally, output results.
  if (outDistanceSqr) {
    *outDistanceSqr = bestDistanceSqr;
  }
  return bestIndex;
}

template <typename Bv>
size_t BvhTree<Bv>::GetNodeCount() const {
  return _nodes.size();
}

template <typename Bv>
RangeByIterators<std::vector<int>::const_iterator> BvhTree<Bv>::GetElements(
    Node const& node) const {
  return _elements.begin() + node.elementIndexRange;
}

template <typename Bv>
int BvhTree<Bv>::BuildNode(int parentIndex, Span<int> elementIndicesSpan, int depth) {
  MOCHI_PROFILE_SCOPE();

  // Fetch new node index.
  int nodeIndex = isize(_nodes);

  // Generate node and setup common terms.
  _nodes.emplace_back();
  _nodes[nodeIndex].parentIndex = parentIndex;
  _nodes[nodeIndex].elementIndexRange = {
      (int)std::distance(_elements.data(), elementIndicesSpan.begin()),
      (int)std::distance(_elements.data(), elementIndicesSpan.end())};
  _levels[depth].push_back(nodeIndex);

  // If maximum recursion has been reached, build leaf node.
  bool const reachedMaxElements = elementIndicesSpan.size() > _params.maxElementsPerLeaf;
  bool const reachedMaximumDepth = (depth + 1) >= _params.maxDepthPerBranch;
  if (!reachedMaxElements || reachedMaximumDepth) {
    _nodes[nodeIndex].isLeafNode = true;
    _nodes[nodeIndex].bv = EncloseShapes(_object, elementIndicesSpan);
    _leaves.push_back(nodeIndex);

    // Ensure local ordering of the elements.
    std::sort(elementIndicesSpan.begin(), elementIndicesSpan.end());
  }

  // Otherwise, determine split and generate branch nodes.
  else {
    // Partition elements according to the selected heuristic.
    // NOTE@Hector: We only have two heuristics at the moment, generalize if necessary.
    auto partition = Partition_TopDown_Mean(
        _object,
        elementIndicesSpan,
        _params.splittingAlgorithm == BvhSplittingAlgorithm::TopDown_AreaWeightedMean);
    auto splittingPoint = elementIndicesSpan.begin() + partition.splittingIndex;
    int numLeftElementIndices = (int)std::distance(elementIndicesSpan.begin(), splittingPoint);
    int numRightElementIndices = (int)std::distance(splittingPoint, elementIndicesSpan.end());

    // Recursively build children.
    auto leftElementIndicesSpan = Span<int>(elementIndicesSpan.begin(), numLeftElementIndices);
    auto rightElementIndicesSpan = Span<int>(splittingPoint, numRightElementIndices);
    _nodes[nodeIndex].bv = partition.bv;
    _nodes[nodeIndex].leftChildIndex = BuildNode(nodeIndex, leftElementIndicesSpan, depth + 1);
    _nodes[nodeIndex].rightChildIndex = BuildNode(nodeIndex, rightElementIndicesSpan, depth + 1);
  }

  // Done!
  return nodeIndex;
}

template <typename Bv>
Bv BvhTree<Bv>::ComputeNodeBv(int index) const {
  auto& node = _nodes[index];
  auto bv = _object->GetBv(_elements[node.elementIndexRange.Min()]);

  auto elemRange = _elements.begin() + node.elementIndexRange;
  for (auto&& e : elemRange) {
    bv = EncloseShapes(bv, _object->GetBv(e));
  }
  return bv;
}

template <typename Bv>
void BvhTree<Bv>::RefitNode(int nodeIndex) {
  auto& node = _nodes[nodeIndex];

  // Refit leaf node.
  if (node.isLeafNode) {
    node.bv = ComputeNodeBv(nodeIndex);
  }
  // Refit interior node.
  else {
    auto const& leftChildNode = _nodes[node.leftChildIndex];
    auto const& rightChildNode = _nodes[node.rightChildIndex];
    node.bv = EncloseShapes(leftChildNode.bv, rightChildNode.bv);
  }
}

template <typename Bv>
void BvhTree<Bv>::QueryNode(Bv const& bv, int nodeIndex, BvhQueryFn const& callback) const {
  auto const& node = _nodes[nodeIndex];

  // If the input bounding volume overlaps the node, proceed.
  if (HasOverlap(bv, node.bv)) {
    // If the leaf node has been reached, test individual leaves and invoke the callback on
    // all the potentially intersecting ones.
    if (node.isLeafNode) {
      auto elemRange = _elements.begin() + node.elementIndexRange;

      for (auto&& e : elemRange) {
        if (HasOverlap(bv, _object->GetBv(e))) {
          callback(e);
        }
      }
    }
    // Otherwise, traverse children.
    else {
      QueryNode(bv, node.leftChildIndex, callback);
      QueryNode(bv, node.rightChildIndex, callback);
    }
  }
}

template <typename Bv>
void BvhTree<Bv>::IntersectNodes(
    BvhTree const& other,
    int thisIndex,
    int otherIndex,
    BvhIntersectionQueryFn const& callback) const {
  MOCHI_PROFILE_SCOPE();
  auto const& thisNode = _nodes[thisIndex];
  auto const& otherNode = other._nodes[otherIndex];

  if (HasOverlap(thisNode.bv, otherNode.bv)) {
    // If both nodes are leaves, test individual entries and determine which are
    // potentially overlapping. Invoke the callback for each overlapping pair.
    if (thisNode.isLeafNode && otherNode.isLeafNode) {
      auto thisRange = _elements.begin() + thisNode.elementIndexRange;
      auto otherRange = other._elements.begin() + otherNode.elementIndexRange;

      for (auto thisE : thisRange) {
        auto thisBv = _object->GetBv(thisE);

        for (auto otherE : otherRange) {
          auto otherBv = other._object->GetBv(otherE);
          if (HasOverlap(thisBv, otherBv)) {
            callback(thisE, otherE);
          }
        }
      }
    }
    // Otherwise, traverse children by recursing over the different branches.
    else if (thisNode.isLeafNode) {
      IntersectNodes(other, thisIndex, otherNode.leftChildIndex, callback);
      IntersectNodes(other, thisIndex, otherNode.rightChildIndex, callback);
    } else if (otherNode.isLeafNode) {
      IntersectNodes(other, thisNode.leftChildIndex, otherIndex, callback);
      IntersectNodes(other, thisNode.rightChildIndex, otherIndex, callback);
    } else {
      IntersectNodes(other, thisNode.leftChildIndex, otherNode.leftChildIndex, callback);
      IntersectNodes(other, thisNode.leftChildIndex, otherNode.rightChildIndex, callback);
      IntersectNodes(other, thisNode.rightChildIndex, otherNode.leftChildIndex, callback);
      IntersectNodes(other, thisNode.rightChildIndex, otherNode.rightChildIndex, callback);
    }
  }
}

template <typename Bv>
void BvhTree<Bv>::FindClosestOnNode(
    int nodeIndex,
    Vec4r point,
    int& bestIndex,
    real& bestDistanceSqr) const {
  auto const& node = _nodes[nodeIndex];

  // Find distance from query point to the BV. If closer than current best candidate, traverse.
  real volumeDistanceSqr = Get0(VDistancePointShapeSqr(point, node.bv));
  if (volumeDistanceSqr < bestDistanceSqr) {
    // Test distance to elements.
    if (node.isLeafNode) {
      auto elemRange = Slice(_elements, node.elementIndexRange);
      for (auto&& elem : elemRange) {
        real distanceSqr = Get0(_object->VGetDistanceSqr(point, elem));
        if (distanceSqr < bestDistanceSqr) {
          bestIndex = elem;
          bestDistanceSqr = distanceSqr;
        }
      }
    }
    // Test distance to children.
    else {
      FindClosestOnNode(node.leftChildIndex, point, bestIndex, bestDistanceSqr);
      FindClosestOnNode(node.rightChildIndex, point, bestIndex, bestDistanceSqr);
    }
  }
}

template <typename Bv>
void BvhTree<Bv>::ShrinkBuffers() {
  MOCHI_PROFILE_SCOPE();

  // Prune empty levels if maximum depth was not reached.
  auto it = std::find_if(_levels.begin(), _levels.end(), [](auto& l) { return l.size() == 0; });
  _levels.erase(it, _levels.end());

  // Shrink buffers to reduce wasted memory.
  _nodes.shrink_to_fit();
  _leaves.shrink_to_fit();
  _elements.shrink_to_fit();
  _levels.shrink_to_fit();
  for (auto& l : _levels) {
    l.shrink_to_fit();
  }
}

