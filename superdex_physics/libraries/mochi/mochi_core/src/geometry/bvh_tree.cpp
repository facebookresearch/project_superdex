template <typename Bv>
TriangularMeshBvhObject<Bv>::TriangularMeshBvhObject(
    std::shared_ptr<TriangularMesh const> const& mesh,
    Span<Real3 const> coordinates) {
  Initialize(mesh, coordinates);
}

template <typename Bv>
void TriangularMeshBvhObject<Bv>::Initialize(
    std::shared_ptr<TriangularMesh const> const& mesh,
    Span<Real3 const> coordinates) {
  MOCHI_PROFILE_SCOPE();
  MOCHI_ASSERT(mesh != nullptr, "Invalid mesh pointer");
  MOCHI_ASSERT(!coordinates || coordinates.size() == mesh->GetNumNodes(), "Invalid coordinates");
  _mesh = mesh;
  _coordinates = coordinates ? coordinates : _mesh->GetNodeCoordinates();
}

template <typename Bv>
bool TriangularMeshBvhObject<Bv>::IsInitialized() const {
  return _mesh != nullptr;
}

template <typename Bv>
int TriangularMeshBvhObject<Bv>::GetNumElements() const {
  return _mesh->GetNumFaces();
}

template <typename Bv>
Bv TriangularMeshBvhObject<Bv>::GetBv(int index) const {
  MOCHI_ASSERT_VERBOSE(index >= 0 && index < _mesh->GetNumFaces(), "Invalid face index");

  Int3 const face = _mesh->GetElementConnectivity()[index];
  Vec4r A = ToSimd(_coordinates[face[0]]);
  Vec4r B = ToSimd(_coordinates[face[1]]);
  Vec4r C = ToSimd(_coordinates[face[2]]);

  Bv outBv;
  GetTriangleBv(A, B, C, outBv);
  return outBv;
}

template <typename Bv>
real TriangularMeshBvhObject<Bv>::GetDistanceSqr(Real3 const& point, int index) const {
  return Get0(VGetDistanceSqr(ToSimd(point), index));
}

template <typename Bv>
Vec4r TriangularMeshBvhObject<Bv>::VGetDistanceSqr(Vec4r point, int index) const {
  MOCHI_ASSERT_VERBOSE(index >= 0 && index < _mesh->GetNumFaces(), "Invalid face index");

  Int3 const face = _mesh->GetElementConnectivity()[index];
  Vec4r A = ToSimd(_coordinates[face[0]]);
  Vec4r B = ToSimd(_coordinates[face[1]]);
  Vec4r C = ToSimd(_coordinates[face[2]]);
  VDistanceSignParams unused;
  return VDistancePointTriangleSqr(point, A, B, C, unused);
}

