/*************************************************************************************************/

static void GetTriangleBv(Vec4r A, Vec4r B, Vec4r C, Aabb& outBv) {
  Vec4r minCoord = Min(A, B, C);
  Vec4r maxCoord = Max(A, B, C);
  outBv = Aabb{minCoord, maxCoord};
}

static void GetTetrahedronBv(Vec4r A, Vec4r B, Vec4r C, Vec4r D, Aabb& outBv) {
  Vec4r minCoord = Min(A, B, C, D);
  Vec4r maxCoord = Max(A, B, C, D);
  outBv = Aabb{minCoord, maxCoord};
}

static void GetPointBv(Real3 p, Aabb& outBv) {
  outBv = Aabb{p, p};
}

static void GetPointBv(Real3 p, Sphere& outBv) {
  outBv = Sphere{p, 0_r};
}

