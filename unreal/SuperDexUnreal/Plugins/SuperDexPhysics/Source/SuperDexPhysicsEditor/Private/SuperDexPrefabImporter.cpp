// If Entry names two links of Actor ("<actor>/<link>", as Mochi names the nested link actors), sets
// OutLinkA and OutLinkB to their names and returns true.
bool FindLinkPair(
    const mochi::prefab::ArticulatedActorPrefab& Actor,
    const mochi::prefab::ActorContactEntry& Entry,
    FName& OutLinkA,
    FName& OutLinkB) {
  if (Actor.name.empty() || Entry.actors.size() != 2) {
    return false;
  }
  const std::string_view actorName(Actor.name);
  auto findLink = [&](const mochi::DynamicString& FullName, FName& OutLink) {
    const std::string_view name(FullName);
    if (name.size() <= actorName.size() + 1 || !name.starts_with(actorName) ||
        name[actorName.size()] != '/') {
      return false;
    }
    const std::string_view linkName = name.substr(actorName.size() + 1);
    for (const auto& link : Actor.links) {
      if (std::string_view(link.name) == linkName) {
        OutLink = FName(ToFString(link.name));
        return true;
      }
    }
    return false;
  };
  return findLink(Entry.actors[0], OutLinkA) && findLink(Entry.actors[1], OutLinkB);
}

bool HasConstraints(const mochi::prefab::ConstraintLists& C) {
  return !C.articulated3dRotationRange.empty() || !C.articulatedSingleDofRange.empty() ||
      !C.articulated3dRotationTarget.empty() || !C.articulatedSingleDofTarget.empty() ||
      !C.jointRotationRange.empty() || !C.jointRotationTracking.empty() ||
      !C.rigidPivotPosition.empty() || !C.rigidPivotToRigidTarget.empty() ||
      !C.rigidPivotRotation.empty() || !C.rigidPrismaticJoint.empty() ||
      !C.rigidSphericalJoint.empty() || !C.deformableNodePosition.empty() ||
      !C.deformableNodeToRigid.empty() || !C.deformableNodeToDeformableNode.empty();
}

// The files a prefab references directly (nested prefabs excluded), as written in the prefab.
TArray<mochi::DynamicString> GetReferencedFiles(const mochi::prefab::ScenePrefab& Prefab) {
  TArray<mochi::DynamicString> files;
  auto addArticulated = [&](const mochi::prefab::ArticulatedActorPrefab& actor) {
    for (const auto& link : actor.links) {
      files.Add(link.shapeFile);
      files.Add(link.renderModelFile);
    }
    if (actor.skin) {
      files.Add(actor.skin->shapeFile);
      files.Add(actor.skin->renderModelFile);
    }
  };
  auto addSoft = [&](const mochi::prefab::SoftActorPrefab& actor) {
    files.Add(actor.shapeFile);
    files.Add(actor.renderModelFile);
    files.Add(actor.flowFile);
  };
  for (const auto& actor : Prefab.actors.rigid) {
    files.Add(actor.shapeFile);
    files.Add(actor.renderModelFile);
  }
  for (const auto& actor : Prefab.actors.soft) {
    addSoft(actor);
  }
  for (const auto& actor : Prefab.actors.articulated) {
    addArticulated(actor);
  }
  for (const auto& actor : Prefab.actors.softSkinned) {
    addArticulated(actor.skeletonParams);
    for (const auto& soft : actor.softParams) {
      addSoft(soft);
    }
  }
  files.RemoveAll([](const mochi::DynamicString& File) { return File.empty(); });
  return files;
}

FString GetRootDir(const FString& SourcePath) {
  const FString rootDir = SuperDexImportUtils::FindSuperDexRootDir(SourcePath);
  return rootDir.IsEmpty() ? FPaths::GetPath(SourcePath) : rootDir;
}

FString ResolvePrefabPath(
    const FString& RootDir,
    const FString& SourcePath,
    const mochi::DynamicString& Path) {
  const std::string root(TCHAR_TO_UTF8(*RootDir));
  const std::string source(TCHAR_TO_UTF8(*SourcePath));
  return SuperDexImportUtils::NormalizePath(
      ToFString(mochi::prefab::GetPrefabFullPath(Path.c_str(), root, source)));
}

mochi::prefab::ScenePrefab LoadPrefab(const FString& SourcePath, bool& bOutSuccess) {
  mochi::ErrorLog error;
  const std::string path(TCHAR_TO_UTF8(*SourcePath));
  mochi::prefab::ScenePrefab prefab = mochi::prefab::ShallowLoadFromFile(path, error);
  bOutSuccess = error.IsOK();
  return prefab;
}

void HashPrefabFiles(const FString& SourcePath, FSHA1& Sha, TSet<FString>& Visited) {
  if (Visited.Contains(SourcePath)) {
    return;
  }
  Visited.Add(SourcePath);
  auto hashFile = [&Sha](const FString& Path) {
    const FTCHARToUTF8 pathUtf8(*Path);
    Sha.Update(reinterpret_cast<const uint8*>(pathUtf8.Get()), pathUtf8.Length());
    TArray<uint8> bytes;
    if (FFileHelper::LoadFileToArray(bytes, *Path, FILEREAD_Silent)) {
      Sha.Update(bytes.GetData(), bytes.Num());
    }
  };
  hashFile(SourcePath);
  bool bLoaded = false;
  const mochi::prefab::ScenePrefab prefab = LoadPrefab(SourcePath, bLoaded);
  if (!bLoaded) {
    return;
  }
  const FString rootDir = GetRootDir(SourcePath);
  for (const mochi::DynamicString& file : GetReferencedFiles(prefab)) {
    hashFile(ResolvePrefabPath(rootDir, SourcePath, file));
  }
  for (const auto& nested : prefab.prefabs) {
    HashPrefabFiles(ResolvePrefabPath(rootDir, SourcePath, nested.path), Sha, Visited);
  }
}

// Adds components to a Blueprint's construction script, under its root.
class FBlueprintOutput : public FSuperDexPrefabImporter::FOutput {
 public:
  FBlueprintOutput(UBlueprint* InBlueprint, USCS_Node* InRoot)
      : Blueprint(InBlueprint), Root(InRoot), UsedNames(GetVariableNames(InBlueprint)) {}

  virtual USceneComponent* AddActor(UClass* ComponentClass, const FString& Name) override {
    return AddNode(Root, ComponentClass, Name);
  }

  virtual USceneComponent*
  AddChild(USceneComponent* Parent, UClass* ComponentClass, const FString& Name) override {
    return AddNode(Nodes.FindChecked(Parent), ComponentClass, Name);
  }

  virtual void AddNestedPrefab(UBlueprint* Nested, const FString& Name, const FTransform& Transform)
      override {
    UChildActorComponent* component =
        CastChecked<UChildActorComponent>(AddActor(UChildActorComponent::StaticClass(), Name));
    component->SetChildActorClass(TSubclassOf<AActor>(Nested->GeneratedClass.Get()));
    component->SetRelativeTransform(Transform);
  }

  virtual AActor* AddSceneActor(UClass* ActorClass, const FString& Name) override {
    return nullptr;
  }

 private:
  USceneComponent* AddNode(USCS_Node* Parent, UClass* ComponentClass, const FString& Name) {
    USCS_Node* node = AddComponentNode(Blueprint, Parent, ComponentClass, Name, UsedNames);
    USceneComponent* component = CastChecked<USceneComponent>(node->ComponentTemplate);
    Nodes.Add(component, node);
    return component;
  }

  UBlueprint* Blueprint;
  USCS_Node* Root;
  TSet<FName> UsedNames;
  TMap<USceneComponent*, USCS_Node*> Nodes;
};

// Spawns an actor per Mochi actor in a level. Components are registered by Finish, once the
// importer has configured them.
class FMapOutput : public FSuperDexPrefabImporter::FOutput {
 public:
  explicit FMapOutput(UWorld* InWorld) : World(InWorld) {}

  virtual USceneComponent* AddActor(UClass* ComponentClass, const FString& Name) override {
    AActor* actor = SpawnActor(AActor::StaticClass(), Name, FTransform::Identity);
    USceneComponent* component = NewObject<USceneComponent>(
        actor, ComponentClass, FName(*SuperDexImportUtils::SanitizeForFileName(Name)));
    actor->SetRootComponent(component);
    actor->AddInstanceComponent(component);
    Components.Add(component);
    return component;
  }

  virtual USceneComponent*
  AddChild(USceneComponent* Parent, UClass* ComponentClass, const FString& Name) override {
    AActor* actor = Parent->GetOwner();
    USceneComponent* component = NewObject<USceneComponent>(
        actor,
        ComponentClass,
        MakeUniqueObjectName(
            actor, ComponentClass, FName(*SuperDexImportUtils::SanitizeForFileName(Name))));
    component->SetupAttachment(Parent);
    actor->AddInstanceComponent(component);
    Components.Add(component);
    return component;
  }

  virtual void AddNestedPrefab(UBlueprint* Nested, const FString& Name, const FTransform& Transform)
      override {
    SpawnActor(Nested->GeneratedClass.Get(), Name, Transform);
  }

  virtual AActor* AddSceneActor(UClass* ActorClass, const FString& Name) override {
    return SpawnActor(ActorClass, Name, FTransform::Identity);
  }

  void Finish() {
    for (USceneComponent* component : Components) {
      component->RegisterComponent();
    }
  }

 private:
  AActor* SpawnActor(UClass* ActorClass, const FString& Label, const FTransform& Transform) {
    AActor* actor = World->SpawnActor<AActor>(ActorClass, Transform, FActorSpawnParameters());
    actor->Tags.Add(kGeneratedTag);
    actor->SetActorLabel(Label);
    return actor;
  }

  UWorld* World;
  TArray<USceneComponent*> Components;
};

