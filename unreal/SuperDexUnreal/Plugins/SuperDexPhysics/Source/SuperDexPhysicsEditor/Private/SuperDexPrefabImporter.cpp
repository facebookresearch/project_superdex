void FSuperDexPrefabImporter::AddSceneSettings(FPrefabContext& Context, FOutput& Output) {
  const FString& prefabName = Context.PrefabName;
  if (Context.Data.contactPairParamsOverrides) {
    WarnUnsupported(prefabName, TEXT("Contact pair params overrides"));
  }
  const bool bHasSceneSettings =
      Context.Data.scene && (Context.Data.scene->gravity || Context.Data.scene->solver);
  if (!bHasSceneSettings && !Context.Data.contactFilter) {
    return;
  }
  AMochiSceneSettingsActor* settings = Cast<AMochiSceneSettingsActor>(
      Output.AddSceneActor(AMochiSceneSettingsActor::StaticClass(), TEXT("MochiSceneSettings")));
  if (!settings) {
    WarnUnsupported(
        prefabName, TEXT("Scene settings and layer contact filters (Blueprint import)"));
    return;
  }
  FMochiSceneSettings& sceneSettings = settings->SceneSettings;
  if (Context.Data.scene) {
    const mochi::prefab::SceneParams& scene = *Context.Data.scene;
    if (scene.gravity) {
      // Gravity is an acceleration [m/s^2]: change its basis but keep its units.
      sceneSettings.GravityVector = M2U.DirectionToUnreal(*scene.gravity);
    }
    if (scene.solver) {
      UMochiSolverParams* solverParams = FindOrCreateAsset<UMochiSolverParams>(
          FPaths::Combine(Context.DestFolder, TEXT("params"), TEXT("MSP_") + prefabName));
      solverParams->FromMochi(*scene.solver);
      solverParams->MarkPackageDirty();
      RecordAsset(Context, solverParams);
      sceneSettings.SolverParams = FSoftObjectPath(solverParams);
    }
  }
  if (Context.Data.contactFilter) {
    const mochi::prefab::ContactFilter& filter = *Context.Data.contactFilter;
    UMochiContactMatrix* contactMatrix = FindOrCreateAsset<UMochiContactMatrix>(
        FPaths::Combine(Context.DestFolder, TEXT("params"), TEXT("MCM_") + prefabName));
    contactMatrix->Matrix.Reset();
    auto addEntries = [&](const auto& Entries, bool bSymmetric) {
      if (!Entries) {
        return;
      }
      for (const mochi::prefab::LayerContactEntry& entry : *Entries) {
        if (entry.layers.size() != 2) {
          UE_LOG(
              LogMochiPhysicsEditor,
              Warning,
              TEXT("[%s] Ignoring a layer contact filter without exactly 2 layers."),
              *prefabName);
          continue;
        }
        FMochiContactMatrixEntry& converted = contactMatrix->Matrix.AddDefaulted_GetRef();
        converted.LayerA = FName(ToFString(entry.layers[0]));
        converted.LayerB = FName(ToFString(entry.layers[1]));
        converted.bEnabled = entry.enable;
        converted.bSymmetric = bSymmetric;
      }
    };
    // Later entries override earlier ones; Mochi applies asymmetric filters first.
    addEntries(filter.layerContactAsymmetric, false);
    addEntries(filter.layerContactSymmetric, true);
    contactMatrix->MarkPackageDirty();
    RecordAsset(Context, contactMatrix);
    sceneSettings.ContactMatrix = FSoftObjectPath(contactMatrix);
    // Link-to-link symmetric actor filters were imported into the articulations.
    int numIgnored =
        filter.actorContactAsymmetric ? static_cast<int>(filter.actorContactAsymmetric->size()) : 0;
    if (filter.actorContactSymmetric) {
      for (const auto& entry : *filter.actorContactSymmetric) {
        bool bImported = false;
        for (const auto& actor : Context.Data.actors.articulated) {
          FName linkA;
          FName linkB;
          bImported = bImported || FindLinkPair(actor, entry, linkA, linkB);
        }
        numIgnored += bImported ? 0 : 1;
      }
    }
    if (numIgnored > 0) {
      WarnUnsupported(
          prefabName,
          FString::Printf(
              TEXT(
                  "Actor contact filters other than symmetric ones between two links of one "
                  "articulation (%d)"),
              numIgnored));
    }
  }
}

//------------------------------------------------------------------------------
// Actors
//------------------------------------------------------------------------------

void FSuperDexPrefabImporter::AddActors(
    FPrefabContext& Context,
    FOutput& Output,
    const TArray<USuperDexPrefab*>& NestedPrefabs) {
  const FString& prefabName = Context.PrefabName;
  const auto& actors = Context.Data.actors;
  for (int i = 0; i < static_cast<int>(actors.rigid.size()); ++i) {
    AddRigidActor(
        Context, Output, actors.rigid[i], GetActorName(actors.rigid[i].name, TEXT("Rigid"), i));
  }
  for (int i = 0; i < static_cast<int>(actors.soft.size()); ++i) {
    AddSoftActor(
        Context, Output, actors.soft[i], GetActorName(actors.soft[i].name, TEXT("Soft"), i));
  }
  for (int i = 0; i < static_cast<int>(actors.articulated.size()); ++i) {
    AddArticulatedActor(
        Context,
        Output,
        actors.articulated[i],
        GetActorName(actors.articulated[i].name, TEXT("Articulated"), i));
  }
  for (int i = 0; i < static_cast<int>(Context.Data.prefabs.size()); ++i) {
    const auto& reference = Context.Data.prefabs[i];
    USuperDexPrefab* nested = NestedPrefabs[i];
    UBlueprint* nestedBlueprint = nested ? nested->GeneratedBlueprint.LoadSynchronous() : nullptr;
    if (!nestedBlueprint || !nestedBlueprint->GeneratedClass) {
      UE_LOG(
          LogMochiPhysicsEditor,
          Error,
          TEXT("[%s] Failed to import nested prefab %s."),
          *prefabName,
          *ToFString(reference.path));
      continue;
    }
    const FString name = reference.name.empty() ? nested->PrefabName : ToFString(reference.name);
    Output.AddNestedPrefab(
        nestedBlueprint,
        name,
        FTransform(
            M2U.RotationToUnreal(reference.rotation),
            M2U.TranslationToUnreal(reference.translation),
            FVector(reference.scale)));
    if (reference.scale != 1_r) {
      bool bLoaded = false;
      if (!LoadPrefab(ResolvePath(Context, reference.path), bLoaded).actors.articulated.empty()) {
        UE_LOG(
            LogMochiPhysicsEditor,
            Warning,
            TEXT("[%s] Nested prefab %s is scaled, but its articulations are not."),
            *prefabName,
            *name);
      }
    }
  }
  if (!actors.softSkinned.empty()) {
    WarnUnsupported(prefabName, TEXT("Soft skinned actors"));
  }
  if (HasConstraints(Context.Data.constraints)) {
    WarnUnsupported(prefabName, TEXT("Constraints"));
  }
  if (!Context.Data.controllers.empty()) {
    WarnUnsupported(prefabName, TEXT("Pose controllers"));
  }
}

void FSuperDexPrefabImporter::AddRigidActor(
    FPrefabContext& Context,
    FOutput& Output,
    const mochi::prefab::RigidActorPrefab& Actor,
    const FString& ActorName) {
  UMochiModel* model = ImportShape(Context, Actor.shapeFile);
  UStaticMesh* renderModel = ImportRenderModel(Context, Actor.renderModelFile);
  const FTransform actorToParent(
      M2U.RotationToUnreal(Actor.rotation), M2U.TranslationToUnreal(Actor.translation));
  const FVector scale = M2U.DirectionToUnreal(Actor.scale).GetAbs();
  // Mochi bakes the actor's scale, then the shape offset, into the shape.
  const FTransform shapeToActor(
      M2U.RotationToUnreal(Actor.shapeRotation),
      M2U.TranslationToUnreal(Actor.shapeTranslation),
      scale);
  // SuperDex Studio renders the model offset in the actor frame, scaled by the actor's scale.
  const FTransform renderToActor(
      M2U.RotationToUnreal(Actor.renderModelRotation),
      M2U.TranslationToUnreal(Actor.renderModelTranslation) * scale,
      M2U.DirectionToUnreal(Actor.renderModelScale).GetAbs() * scale);
  const bool bNonUniformScale = !scale.AllComponentsEqual();

  if (!model) {
    if (renderModel) {
      UE_LOG(
          LogMochiPhysicsEditor,
          Warning,
          TEXT("[%s] Rigid actor %s has no Mochi shape; only its render model was imported."),
          *Context.PrefabName,
          *ActorName);
      UStaticMeshComponent* component = CastChecked<UStaticMeshComponent>(
          Output.AddActor(UStaticMeshComponent::StaticClass(), ActorName));
      component->SetStaticMesh(renderModel);
      component->SetRelativeTransform(renderToActor * actorToParent);
    }
    return;
  }

  UMochiRigidMeshComponent* component = CastChecked<UMochiRigidMeshComponent>(
      Output.AddActor(UMochiRigidMeshComponent::StaticClass(), ActorName));
  component->SetRelativeTransform(shapeToActor * actorToParent);
  component->Model = model;
  component->bIsStatic = Actor.isStatic;
  component->bHasGravity = Actor.hasGravity;
  if (!Actor.layer.empty()) {
    component->Layer = FName(ToFString(Actor.layer));
  }
  component->ColliderType = static_cast<EMochiColliderType>(Actor.colliderType);
  component->BoundaryElementType = FromMochi(Actor.boundaryElementType);
  component->bEnableBoundarySubsampling = Actor.boundarySubsampling.has_value();
  if (Actor.boundarySubsampling) {
    component->BoundarySubsamplingParams = FromMochi(*Actor.boundarySubsampling);
  }
  if (Actor.density) {
    UMochiMaterialParams* candidate = NewObject<UMochiMaterialParams>(GetTransientPackage());
    candidate->Density = *Actor.density;
    component->MaterialParams = FindOrCreateMaterialParams(Context, candidate, ActorName);
  }
  component->ContactParams = FindOrCreateContactParams(Context, Actor.contact, ActorName);
  // Mochi scales mass property overrides with the actor.
  std::optional<mochi::Real3> centerOfMass = Actor.centerOfMass;
  std::optional<mochi::real> mass = Actor.mass;
  std::optional<mochi::Real6> momentOfInertia = Actor.momentOfInertia;
  ApplyDiagonalScaleToInertia(centerOfMass, mass, momentOfInertia, Actor.scale);
  component->bOverrideMass = mass.has_value();
  component->Mass = mass.value_or(0);
  if (centerOfMass && momentOfInertia) {
    component->bOverrideInertialParams = true;
    component->CenterOfMass = M2U.TranslationToUnreal(*centerOfMass);
    component->MomentOfInertia = M2U.InertiaToUnreal(*momentOfInertia);
  } else if (centerOfMass || momentOfInertia) {
    UE_LOG(
        LogMochiPhysicsEditor,
        Warning,
        TEXT(
            "[%s] Rigid actor %s overrides only one of its center of mass and moment of inertia, "
            "which Unreal can only override together; both were ignored."),
        *Context.PrefabName,
        *ActorName);
  }
  if (Actor.linearVelocity || Actor.angularVelocity) {
    WarnUnsupported(
        Context.PrefabName, FString::Printf(TEXT("Initial velocity of %s"), *ActorName));
  }

  if (!renderModel) {
    return;
  }
  // The rigid component renders its static mesh in the shape frame. Use it directly when the render
  // model coincides with the shape, otherwise attach the render model as a child component.
  if (renderToActor.Equals(shapeToActor)) {
    component->SetStaticMesh(renderModel);
    return;
  }
  if (bNonUniformScale &&
      (!renderToActor.GetRotation().IsIdentity() || !shapeToActor.GetRotation().IsIdentity())) {
    UE_LOG(
        LogMochiPhysicsEditor,
        Warning,
        TEXT(
            "[%s] Rigid actor %s combines a non-uniform scale with rotated model offsets, which "
            "Unreal's transform hierarchy can only approximate."),
        *Context.PrefabName,
        *ActorName);
  }
  UStaticMeshComponent* visual = CastChecked<UStaticMeshComponent>(
      Output.AddChild(component, UStaticMeshComponent::StaticClass(), ActorName + TEXT("_Visual")));
  visual->SetStaticMesh(renderModel);
  visual->SetRelativeTransform(renderToActor.GetRelativeTransform(shapeToActor));
}

void FSuperDexPrefabImporter::AddSoftActor(
    FPrefabContext& Context,
    FOutput& Output,
    const mochi::prefab::SoftActorPrefab& Actor,
    const FString& ActorName) {
  const FString& prefabName = Context.PrefabName;
  UMochiModel* model = ImportShape(Context, Actor.shapeFile);
  if (!model) {
    UE_LOG(
        LogMochiPhysicsEditor,
        Warning,
        TEXT("[%s] Soft actor %s has no Mochi shape and was skipped."),
        *prefabName,
        *ActorName);
    return;
  }
  if (!Actor.renderModelFile.empty()) {
    WarnUnsupported(prefabName, FString::Printf(TEXT("Render model of soft actor %s"), *ActorName));
  }
  if (!Actor.flowFile.empty()) {
    WarnUnsupported(prefabName, FString::Printf(TEXT("Flow of soft actor %s"), *ActorName));
  }
  if (!Actor.hasInertia || !Actor.hasStress) {
    WarnUnsupported(
        prefabName,
        FString::Printf(TEXT("Disabled inertia or stress of soft actor %s"), *ActorName));
  }

  UMochiSoftMeshComponent* component = CastChecked<UMochiSoftMeshComponent>(
      Output.AddActor(UMochiSoftMeshComponent::StaticClass(), ActorName));
  const FTransform actorToParent(
      M2U.RotationToUnreal(Actor.rotation), M2U.TranslationToUnreal(Actor.translation));
  const FTransform shapeToActor(
      M2U.RotationToUnreal(Actor.shapeRotation),
      M2U.TranslationToUnreal(Actor.shapeTranslation),
      M2U.DirectionToUnreal(Actor.scale).GetAbs());
  component->SetRelativeTransform(shapeToActor * actorToParent);
  component->Model = model;
  component->bHasGravity = Actor.hasGravity;
  if (!Actor.layer.empty()) {
    component->Layer = FName(ToFString(Actor.layer));
  }
  component->ColliderType = static_cast<EMochiColliderType>(Actor.colliderType);
  component->BoundaryElementType = FromMochi(Actor.boundaryElementType);
  component->bUseContactSkin = Actor.useContactSkin;
  component->bUseRecentering = Actor.useRecentering;
  UMochiMaterialParams* candidate = NewObject<UMochiMaterialParams>(GetTransientPackage());
  candidate->FromMochi(Actor.material);
  component->MaterialParams = FindOrCreateMaterialParams(Context, candidate, ActorName);
  component->ContactParams = FindOrCreateContactParams(Context, Actor.contact, ActorName);
}

void FSuperDexPrefabImporter::AddArticulatedActor(
    FPrefabContext& Context,
    FOutput& Output,
    const mochi::prefab::ArticulatedActorPrefab& Actor,
    const FString& ActorName) {
  UMochiArticulation* articulation = ImportArticulation(Context, Actor, ActorName);
  UMochiArticulationComponent* component = CastChecked<UMochiArticulationComponent>(
      Output.AddActor(UMochiArticulationComponent::StaticClass(), ActorName));
  component->SetRelativeTransform(
      FTransform(M2U.RotationToUnreal(Actor.rotation), M2U.TranslationToUnreal(Actor.translation)));
  component->SetArticulationAsset(articulation);

  if (Actor.jointVelocities && !Actor.jointVelocities->empty()) {
    // Mochi's layout includes the 6 DOFs of a Free root joint; the component's doesn't.
    TArray<EMochiArticulatedJointType> types;
    for (const FMochiArticulatedJoint& joint : articulation->GetJoints()) {
      types.Add(joint.Type);
    }
    TArray<double> velocities;
    for (const mochi::real velocity : *Actor.jointVelocities) {
      velocities.Add(velocity);
    }
    ConvertArticulatedDofsToUnreal(types, true, velocities, M2U);
    if (!types.IsEmpty() && types[0] == EMochiArticulatedJointType::Free) {
      velocities.RemoveAt(0, FMath::Min(6, velocities.Num()));
    }
    if (velocities.Num() == articulation->GetNumDofs()) {
      component->InitialJointVelocities = MoveTemp(velocities);
    } else {
      UE_LOG(
          LogMochiPhysicsEditor,
          Warning,
          TEXT("[%s] Articulation %s has %d joint velocities but %d DOFs; they were ignored."),
          *Context.PrefabName,
          *ActorName,
          velocities.Num(),
          articulation->GetNumDofs());
    }
  }
}
