// Changing what the importer generates should bump this so existing imports are regenerated.
constexpr const TCHAR* kImporterVersion = TEXT("3");
// Tags the Blueprint components and map actors generated by the importer, which are replaced on
// reimport.
const FName kGeneratedTag(TEXT("SuperDexPrefabGenerated"));
// The same tag as written by imports made before prefabs were named SuperDex prefabs. Reimport
// replaces what carries it too.
const FName kLegacyGeneratedTag(TEXT("MochiPrefabGenerated"));
// Name prefix of USuperDexPrefab assets, and the prefix of assets imported before the rename, which
// reimport keeps using.
constexpr const TCHAR* kPrefabAssetPrefix = TEXT("SDP_");
constexpr const TCHAR* kLegacyPrefabAssetPrefix = TEXT("MP_");

bool IsGenerated(const AActor* Actor) {
  return Actor->ActorHasTag(kGeneratedTag) || Actor->ActorHasTag(kLegacyGeneratedTag);
}

bool IsGenerated(const UActorComponent* Component) {
  return Component->ComponentHasTag(kGeneratedTag) ||
      Component->ComponentHasTag(kLegacyGeneratedTag);
}

