template <typename TParams>
TParams* FSuperDexPrefabImporter::FindOrCreateParams(
    FPrefabContext& Context,
    const TParams* Candidate,
    TArray<TParams*>& Existing,
    const FString& Prefix,
    const FString& OwnerName) {
  // Default params are left unset, and identical params share one asset.
  if (HaveSameProperties(Candidate, GetDefault<TParams>())) {
    return nullptr;
  }
  if (TParams* const* found = Existing.FindByPredicate(
          [&](const TParams* Params) { return HaveSameProperties(Candidate, Params); })) {
    return *found;
  }
  TParams* asset = FindOrCreateAsset<TParams>(FPaths::Combine(
      Context.DestFolder,
      TEXT("params"),
      Prefix +
          MakeUniqueAssetName(
              Context, Prefix, SuperDexImportUtils::SanitizeForFileName(OwnerName))));
  CopyProperties(asset, Candidate);
  asset->MarkPackageDirty();
  RecordAsset(Context, asset);
  Existing.Add(asset);
  return asset;
}

UMochiContactParams* FSuperDexPrefabImporter::FindOrCreateContactParams(
    FPrefabContext& Context,
    const mochi::ContactParams& Params,
    const FString& OwnerName) {
  UMochiContactParams* candidate = NewObject<UMochiContactParams>(GetTransientPackage());
  candidate->FromMochi(Params);
  return FindOrCreateParams(Context, candidate, Context.ContactParams, TEXT("MCP_"), OwnerName);
}

UMochiMaterialParams* FSuperDexPrefabImporter::FindOrCreateMaterialParams(
    FPrefabContext& Context,
    const UMochiMaterialParams* Candidate,
    const FString& OwnerName) {
  return FindOrCreateParams(
      Context, Candidate, Context.MaterialParams, TEXT("MMP_"), OwnerName + TEXT("_Material"));
}

UMochiArticulation* FSuperDexPrefabImporter::ImportArticulation(
    FPrefabContext& Context,
    const mochi::prefab::ArticulatedActorPrefab& Actor,
    const FString& ActorName) {
  // Mochi bakes the articulation's uniform scale into its link frames and shapes when it adds the
  // prefab to a scene; do the same, since UMochiArticulationComponent doesn't scale.
  const mochi::real scale = Actor.scale;
  auto scaleTranslation = [scale](const mochi::TransformRT& T) {
    return mochi::TransformRT(T.GetRotation(), T.GetTranslation() * scale);
  };
  TArray<FMochiArticulatedJoint> joints;
  for (int i = 0; i < static_cast<int>(Actor.joints.size()); ++i) {
    mochi::ArticulatedJointParams joint = Actor.joints[i];
    joint.parentLinkFromJoint = scaleTranslation(joint.parentLinkFromJoint);
    if (joint.type == mochi::ArticulatedJointType::Prismatic) {
      if (joint.minLimit) {
        *joint.minLimit *= scale;
      }
      if (joint.maxLimit) {
        *joint.maxLimit *= scale;
      }
    }
    FMochiArticulatedJoint& converted = joints.AddDefaulted_GetRef();
    converted.FromMochi(joint, M2U);
    if (converted.Name.IsNone()) {
      converted.Name = FName(FString::Printf(TEXT("joint_%d"), i));
    }
  }

  TArray<FMochiArticulatedLink> links;
  for (int i = 0; i < static_cast<int>(Actor.links.size()); ++i) {
    mochi::prefab::ArticulatedLinkPrefab link = Actor.links[i];
    link.parentJointFromLink = scaleTranslation(link.parentJointFromLink);
    mochi::Real3 massScale{scale, scale, scale};
    if (!link.shapeFile.empty()) {
      massScale *= link.shapeScale;
    }
    ApplyDiagonalScaleToInertia(link.centerOfMass, link.mass, link.momentOfInertia, massScale);
    link.shapeScale *= scale;
    link.shapeTranslation *= scale;
    link.renderModelScale *= scale;
    link.renderModelTranslation *= scale;
    FMochiArticulatedLink& converted = links.AddDefaulted_GetRef();
    converted.FromMochi(link, M2U);
    if (converted.Name.IsNone()) {
      converted.Name = FName(FString::Printf(TEXT("link_%d"), i));
    }
    converted.Shape = ImportShape(Context, link.shapeFile);
    converted.RenderModel = ImportRenderModel(Context, link.renderModelFile);
    converted.ContactParams = FindOrCreateContactParams(
        Context, link.contact, ActorName + TEXT("_") + converted.Name.ToString());
  }

  TArray<FMochiArticulatedCycleJoint> cycles;
  for (mochi::ArticulatedCycleJointParams cycle : Actor.cycles) {
    cycle.jointFromChildLink = scaleTranslation(cycle.jointFromChildLink);
    cycles.AddDefaulted_GetRef().FromMochi(cycle, M2U);
  }

  TOptional<FMochiArticulatedSkin> skin;
  if (Actor.skin) {
    skin.Emplace();
    skin->FromMochi(*Actor.skin);
    skin->Shape = ImportShape(Context, Actor.skin->shapeFile);
    skin->ContactParams =
        FindOrCreateContactParams(Context, Actor.skin->contact, ActorName + TEXT("_Skin"));
  }

  UMochiArticulation* articulation = FindOrCreateAsset<UMochiArticulation>(FPaths::Combine(
      Context.DestFolder,
      TEXT("MA_") +
          MakeUniqueAssetName(
              Context, TEXT("MA_"), SuperDexImportUtils::SanitizeForFileName(ActorName))));
  articulation->SetDefinition(
      ActorName, MoveTemp(joints), MoveTemp(links), MoveTemp(cycles), skin.GetPtrOrNull());
  // Symmetric actor contact filters between two of the articulation's links become its contact
  // overrides, which the runtime applies after the links are created, as Mochi applies the filter.
  TArray<FMochiArticulationContactOverride> contactOverrides;
  if (Context.Data.contactFilter && Context.Data.contactFilter->actorContactSymmetric) {
    for (const auto& entry : *Context.Data.contactFilter->actorContactSymmetric) {
      FMochiArticulationContactOverride contact;
      if (FindLinkPair(Actor, entry, contact.LinkAName, contact.LinkBName)) {
        contact.bEnable = entry.enable;
        contactOverrides.Add(contact);
      }
    }
  }
  articulation->SetContactOverrides(MoveTemp(contactOverrides));
  articulation->MarkPackageDirty();
  RecordAsset(Context, articulation);

  // The skeletal mesh goes with the link render meshes, as for bots.
  FMochiArticulationAssetUtils::GenerateSkeletalMesh(
      articulation, FPaths::Combine(Context.DestFolder, TEXT("render")));
  if (USkeletalMesh* skeletalMesh = articulation->GetSkeletalMesh()) {
    RecordAsset(Context, skeletalMesh);
    RecordAsset(Context, skeletalMesh->GetSkeleton());
    for (const FSkeletalMaterial& material : skeletalMesh->GetMaterials()) {
      RecordAsset(Context, material.MaterialInterface);
    }
  } else {
    UE_LOG(
        LogMochiPhysicsEditor,
        Warning,
        TEXT("[%s] Failed to generate the skeletal mesh of articulation %s."),
        *Context.PrefabName,
        *ActorName);
  }
  return articulation;
}

//------------------------------------------------------------------------------
// Map
//------------------------------------------------------------------------------

UWorld* FSuperDexPrefabImporter::BuildMap(
    const FString& PackagePath,
    TFunctionRef<void(FOutput&)> Populate) {
  const FString assetName = FPackageName::GetLongPackageAssetName(PackagePath);
  UWorld* world = LoadObject<UWorld>(
      nullptr, *(PackagePath + TEXT(".") + assetName), nullptr, LOAD_NoWarn | LOAD_Quiet);
  // A map open in the editor is edited in place and left for the user to save. Any other map is
  // initialized only while it is built, then saved and cleaned up so the editor can open it.
  const bool bOpenInEditor = world && GEditor && world == GEditor->GetEditorWorldContext().World();
  if (world && world->PersistentLevel && world->PersistentLevel->OwningWorld &&
      world->PersistentLevel->OwningWorld != world) {
    UE_LOG(
        LogMochiPhysicsEditor,
        Error,
        TEXT("Map %s is loaded as a sublevel of %s; unload it and reimport."),
        *world->GetPathName(),
        *world->PersistentLevel->OwningWorld->GetPathName());
    return nullptr;
  }
  bool bInitializedHere = false;
  bool bCreatedHere = false;
  if (world) {
    if (!world->bIsWorldInitialized) {
      world->InitWorld(GetMapBuildInitializationValues());
      bInitializedHere = true;
    }
    TArray<AActor*> generatedActors;
    for (TActorIterator<AActor> it(world); it; ++it) {
      if (IsGenerated(*it)) {
        generatedActors.Add(*it);
      }
    }
    for (AActor* actor : generatedActors) {
      world->EditorDestroyActor(actor, true);
    }
  } else {
    UPackage* package = CreatePackage(*PackagePath);
    package->ThisContainsMap();
    const UWorld::InitializationValues initValues = GetMapBuildInitializationValues();
    const FSoftObjectPath& templatePath = GetDefault<UMochiPhysicsSettings>()->PrefabMapTemplate;
    UWorld* templateWorld = Cast<UWorld>(templatePath.TryLoad());
    // Duplicating a world only copies its own package.
    if (templateWorld &&
        (templateWorld->GetWorldPartition() ||
         templateWorld->PersistentLevel->IsUsingExternalActors())) {
      UE_LOG(
          LogMochiPhysicsEditor,
          Warning,
          TEXT("Map template %s uses World Partition or external actors; creating an empty map."),
          *templatePath.ToString());
    } else if (templateWorld) {
      FObjectDuplicationParameters params(templateWorld, package);
      params.DestName = FName(*assetName);
      params.DuplicateMode = EDuplicateMode::World;
      world = Cast<UWorld>(StaticDuplicateObjectEx(params));
      if (world) {
        world->WorldType = EWorldType::Inactive;
        // The template's baked lighting belongs to the template.
        world->PersistentLevel->MapBuildData = nullptr;
        world->InitWorld(initValues);
      } else {
        UE_LOG(
            LogMochiPhysicsEditor,
            Warning,
            TEXT("Failed to copy map template %s; creating an empty map."),
            *templatePath.ToString());
      }
    } else if (!templatePath.IsNull()) {
      UE_LOG(
          LogMochiPhysicsEditor,
          Warning,
          TEXT("Map template %s not found; creating an empty map."),
          *templatePath.ToString());
    }
    if (!world) {
      world = UWorld::CreateWorld(
          EWorldType::Inactive,
          false,
          FName(*assetName),
          package,
          /*bAddToRoot=*/false,
          ERHIFeatureLevel::Num,
          &initValues);
    }
    if (!world) {
      UE_LOG(LogMochiPhysicsEditor, Error, TEXT("Failed to create map %s."), *PackagePath);
      return nullptr;
    }
    bInitializedHere = true;
    bCreatedHere = true;
    world->SetFlags(RF_Public | RF_Standalone);
    if (GEditor) {
      GEditor->InitBuilderBrush(world);
    }
    FAssetRegistryModule::AssetCreated(world);
  }

  FMapOutput output(world);
  Populate(output);
  output.Finish();
  world->MarkPackageDirty();

  bool bSaved = true;
  if (!bOpenInEditor) {
    const FString filename = FPackageName::LongPackageNameToFilename(
        PackagePath, FPackageName::GetMapPackageExtension());
    FSavePackageArgs saveArgs;
    saveArgs.TopLevelFlags = RF_Standalone;
    bSaved = UPackage::SavePackage(world->GetOutermost(), world, *filename, saveArgs);
    if (!bSaved) {
      UE_LOG(LogMochiPhysicsEditor, Error, TEXT("Failed to save map %s."), *filename);
    }
  }
  if (bInitializedHere) {
    world->CleanupWorld();
  }
  if (!bSaved && bCreatedHere) {
    // Don't leave a map without a file behind.
    FAssetRegistryModule::AssetDeleted(world);
    world->ClearFlags(RF_Public | RF_Standalone);
    world->MarkAsGarbage();
  }
  return bSaved ? world : nullptr;
}

//------------------------------------------------------------------------------
// Blueprint
//------------------------------------------------------------------------------

UBlueprint* FSuperDexPrefabImporter::BuildBlueprint(
    const FString& PackagePath,
    TFunctionRef<void(FOutput&)> Populate) {
  UBlueprint* blueprint =
      LoadObject<UBlueprint>(nullptr, *PackagePath, nullptr, LOAD_NoWarn | LOAD_Quiet);
  if (!blueprint) {
    UPackage* package = CreatePackage(*PackagePath);
    blueprint = FKismetEditorUtilities::CreateBlueprint(
        AActor::StaticClass(),
        package,
        FName(*FPackageName::GetLongPackageAssetName(PackagePath)),
        EBlueprintType::BPTYPE_Normal,
        UBlueprint::StaticClass(),
        UBlueprintGeneratedClass::StaticClass(),
        FName(TEXT("SuperDexPrefabImporter")));
    if (!blueprint || !blueprint->SimpleConstructionScript) {
      UE_LOG(LogMochiPhysicsEditor, Error, TEXT("Failed to create Blueprint %s."), *PackagePath);
      return nullptr;
    }
    FAssetRegistryModule::AssetCreated(blueprint);
  }
  USimpleConstructionScript* scs = blueprint->SimpleConstructionScript;

  // Replace the components generated by the previous import.
  for (USCS_Node* node : TArray<USCS_Node*>(scs->GetAllNodes())) {
    if (node->ComponentTemplate && IsGenerated(node->ComponentTemplate)) {
      scs->RemoveNodeAndPromoteChildren(node);
    }
  }
  USCS_Node* root = scs->GetDefaultSceneRootNode();
  if (!root && !scs->GetRootNodes().IsEmpty()) {
    root = scs->GetRootNodes()[0];
  }
  if (!root) {
    root = scs->CreateNode(USceneComponent::StaticClass(), FName(TEXT("Root")));
    scs->AddNode(root);
  }

  FBlueprintOutput output(blueprint, root);
  Populate(output);

  FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(blueprint);
  FKismetEditorUtilities::CompileBlueprint(blueprint);
  blueprint->MarkPackageDirty();
  return blueprint;
}

