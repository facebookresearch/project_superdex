FString FSuperDexPrefabImporter::GetDestinationFolder(
    const FString& SourcePath,
    const FString& FallbackFolder) {
  const UMochiPhysicsSettings* settings = GetDefault<UMochiPhysicsSettings>();
  if (settings->bOrganizePrefabsInRootFolder) {
    const FString rootFolder = settings->PrefabRootFolder.Path.IsEmpty()
        ? TEXT("/Game/Prefabs")
        : settings->PrefabRootFolder.Path;
    const FString folder =
        SuperDexImportUtils::ComputeDestinationPackagePath(SourcePath, rootFolder);
    if (!folder.IsEmpty()) {
      return folder;
    }
  }
  return FallbackFolder;
}

USuperDexPrefab* FSuperDexPrefabImporter::FindPrefabAsset(
    const FString& DestFolder,
    const FString& PrefabName) {
  for (const TCHAR* prefix : {kPrefabAssetPrefix, kLegacyPrefabAssetPrefix}) {
    if (USuperDexPrefab* prefab = LoadObject<USuperDexPrefab>(
            nullptr,
            *FPaths::Combine(DestFolder, prefix + PrefabName),
            nullptr,
            LOAD_NoWarn | LOAD_Quiet)) {
      return prefab;
    }
  }
  return nullptr;
}

USuperDexPrefab* FSuperDexPrefabImporter::CreatePrefabAsset(
    const FString& DestFolder,
    const FString& PrefabName) {
  const FString assetName = kPrefabAssetPrefix + PrefabName;
  USuperDexPrefab* prefab = NewObject<USuperDexPrefab>(
      CreatePackage(*FPaths::Combine(DestFolder, assetName)),
      FName(*assetName),
      RF_Public | RF_Standalone);
  FAssetRegistryModule::AssetCreated(prefab);
  return prefab;
}

FString FSuperDexPrefabImporter::ComputeSourceHash(const FString& SourcePath) {
  FSHA1 sha;
  const FTCHARToUTF8 version(kImporterVersion);
  sha.Update(reinterpret_cast<const uint8*>(version.Get()), version.Length());
  TSet<FString> visited;
  HashPrefabFiles(SourcePath, sha, visited);
  sha.Final();
  FSHAHash hash;
  sha.GetHash(hash.Hash);
  return hash.ToString();
}

bool FSuperDexPrefabImporter::AreGeneratedAssetsPresent(const USuperDexPrefab* Prefab) {
  if (!Prefab->AssetImportData || Prefab->AssetImportData->GeneratedAssetPaths.IsEmpty()) {
    return false;
  }
  const bool bOutputPresent = Prefab->ImportMode == ESuperDexPrefabImportMode::Blueprint
      ? Prefab->GeneratedBlueprint.LoadSynchronous() != nullptr
      : Prefab->GeneratedMap.LoadSynchronous() != nullptr;
  if (!bOutputPresent) {
    return false;
  }
  for (const USuperDexPrefab* nested : Prefab->NestedPrefabs) {
    if (!nested || !AreGeneratedAssetsPresent(nested)) {
      return false;
    }
  }
  const FString folder = FPackageName::GetLongPackagePath(Prefab->GetOutermost()->GetName());
  for (const FString& relPath : Prefab->AssetImportData->GeneratedAssetPaths) {
    const FString objectPath = FPaths::Combine(folder, relPath);
    if (!LoadObject<UObject>(nullptr, *objectPath, nullptr, LOAD_NoWarn | LOAD_Quiet)) {
      UE_LOG(LogMochiPhysicsEditor, Display, TEXT("Generated asset missing: %s"), *objectPath);
      return false;
    }
  }
  return true;
}

bool FSuperDexPrefabImporter::IsUpToDate(const USuperDexPrefab* Prefab) {
  const FString sourcePath = Prefab->GetSourceFilePath();
  return !sourcePath.IsEmpty() && Prefab->AssetImportData &&
      Prefab->AssetImportData->SourceFileHash == ComputeSourceHash(sourcePath) &&
      AreGeneratedAssetsPresent(Prefab);
}

bool FSuperDexPrefabImporter::LoadContext(
    FPrefabContext& Context,
    const FString& SourcePath,
    const FString& DestFolder) {
  Context.PrefabName = GetPrefabName(SourcePath);
  Context.SourcePath = SourcePath;
  Context.RootDir = GetRootDir(SourcePath);
  Context.DestFolder = DestFolder;
  bool bLoaded = false;
  Context.Data = LoadPrefab(SourcePath, bLoaded);
  if (!bLoaded) {
    UE_LOG(LogMochiPhysicsEditor, Error, TEXT("Failed to load prefab %s."), *SourcePath);
  }
  return bLoaded;
}

FString FSuperDexPrefabImporter::ResolvePath(
    const FPrefabContext& Context,
    const mochi::DynamicString& Path) const {
  return ResolvePrefabPath(Context.RootDir, Context.SourcePath, Path);
}

FString FSuperDexPrefabImporter::MakeAssetName(
    FPrefabContext& Context,
    const FString& Prefix,
    const FString& BaseName,
    const FString& SourcePath) const {
  FString name = BaseName;
  for (int i = 1; Context.AssetSources.FindOrAdd(Prefix + name, SourcePath) != SourcePath; ++i) {
    name = FString::Printf(TEXT("%s_%d"), *BaseName, i);
  }
  return name;
}

FString FSuperDexPrefabImporter::MakeUniqueAssetName(
    FPrefabContext& Context,
    const FString& Prefix,
    const FString& BaseName) const {
  return MakeAssetName(
      Context, Prefix, BaseName, FString::Printf(TEXT("#%d"), Context.AssetSources.Num()));
}

void FSuperDexPrefabImporter::RecordGeneratedAsset(
    const FString& Folder,
    const UObject* Asset,
    TArray<FString>& OutPaths) {
  if (!Asset) {
    return;
  }
  const FString folderPrefix = Folder + TEXT("/");
  const FString objectPath = Asset->GetPathName();
  if (objectPath.StartsWith(folderPrefix)) {
    OutPaths.AddUnique(objectPath.RightChop(folderPrefix.Len()));
  }
}

bool FSuperDexPrefabImporter::IsOutputTaken(
    const FString& PackagePath,
    const FSoftObjectPath& CurrentOutput) {
  if (CurrentOutput.GetLongPackageName() == PackagePath) {
    return false;
  }
  const FString objectPath =
      PackagePath + TEXT(".") + FPackageName::GetLongPackageAssetName(PackagePath);
  if (!LoadObject<UObject>(nullptr, *objectPath, nullptr, LOAD_NoWarn | LOAD_Quiet)) {
    return false;
  }
  UE_LOG(
      LogMochiPhysicsEditor,
      Error,
      TEXT("%s already exists and was not generated by this import. Delete or rename it."),
      *PackagePath);
  return true;
}

void FSuperDexPrefabImporter::RecordAsset(FPrefabContext& Context, const UObject* Asset) const {
  RecordGeneratedAsset(Context.DestFolder, Asset, Context.GeneratedAssetPaths);
}

void FSuperDexPrefabImporter::RecordMeshAndMaterials(
    FPrefabContext& Context,
    const UStaticMesh* Mesh) const {
  if (Mesh) {
    RecordAsset(Context, Mesh);
    for (const FStaticMaterial& material : Mesh->GetStaticMaterials()) {
      RecordAsset(Context, material.MaterialInterface);
    }
  }
}

