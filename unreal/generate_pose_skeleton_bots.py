"""Generate the pose skeleton bots that SuperDexPose embeds.

Every pose skeleton (Skeletons/SuperDexSkeleton_*.h) is the skeleton of a hand bot in
assets/bots/hands, and a pose on it holds that bot's joint positions. SuperDexPose embeds a pruned
copy of each bot, one per hand, so that pose sources work without imported content: every link and
joint with its kinematics (type, frame, axis, limits) and the default pose, but no geometry,
contact, mass or friction. A bot's DOFs are therefore exactly those of the bot it was pruned from.

The highpoly and lowpoly variants of a hand bot share their kinematics, which this script checks.

Usage
-----
    python generate_pose_skeleton_bots.py [--check]

Writes SuperDexRobotics/Source/SuperDexPose/Private/Skeletons/SuperDexSkeletonBotJson.h.
With --check, writes nothing and exits with 1 if that file is out of date.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

_UNREAL_DIR = Path(__file__).resolve().parent
_BOTS_DIR = _UNREAL_DIR.parent / "assets" / "bots" / "hands"
_OUTPUT = (
    _UNREAL_DIR
    / "SuperDexUnreal/Plugins/SuperDexRobotics/Source/SuperDexPose/Private/Skeletons"
    / "SuperDexSkeletonBotJson.h"
)

# (C++ skeleton name, bot directory, bot file stem) of every pose skeleton.
_SKELETONS = [
    ("OpenXR", "openxr", "openxr_hand"),
    ("OculusXR", "oculus_xr", "oculus_xr_hand"),
]
_SIDES = [("Left", "left"), ("Right", "right")]
_VARIANTS = ["highpoly", "lowpoly"]

# What a pruned bot keeps of each link and joint.
_LINK_KEYS = ["name", "parentLink"]
_JOINT_KEYS = ["name", "type", "parentLinkFromJoint", "axis", "minLimit", "maxLimit"]


def _prune(bot: dict, name: str) -> dict:
    return {
        "name": name,
        "links": [
            {k: link[k] for k in _LINK_KEYS if k in link} for link in bot["links"]
        ],
        "joints": [
            {k: joint[k] for k in _JOINT_KEYS if k in joint} for joint in bot["joints"]
        ],
        "defaultPose": bot["defaultPose"],
    }


def _load_pruned(directory: str, stem: str, side: str) -> dict:
    name = f"{stem}_{side}"
    pruned = None
    for variant in _VARIANTS:
        path = _BOTS_DIR / directory / side / f"{stem}_{variant}_{side}.superdex_bot"
        candidate = _prune(json.loads(path.read_text()), name)
        if pruned is not None and candidate != pruned:
            raise ValueError(
                f"{path} does not have the kinematics of the other {name} variants"
            )
        pruned = candidate
    assert pruned is not None
    return pruned


def _to_cpp(variable: str, bot: dict) -> str:
    # One raw string literal per line keeps each literal under MSVC's length limit.
    lines = [
        json.dumps({k: v for k, v in bot.items() if k not in ("links", "joints")})[:-1]
        + ",",
        '"links": [',
    ]
    for i, link in enumerate(bot["links"]):
        lines.append(
            "  " + json.dumps(link) + ("," if i + 1 < len(bot["links"]) else "")
        )
    lines.append('], "joints": [')
    for i, joint in enumerate(bot["joints"]):
        lines.append(
            "  " + json.dumps(joint) + ("," if i + 1 < len(bot["joints"]) else "")
        )
    lines.append("]}")
    body = "\n".join(f'    R"json({line})json"' for line in lines)
    return f"static const char* const {variable} =\n{body};\n"


def generate() -> str:
    parts = [
        "// Copyright (c) Meta Platforms, Inc. and affiliates.\n",
        "//\n",
        "// "
        + "@"
        + "generated by arvr/projects/superdex/unreal/generate_pose_skeleton_bots.py\n",
        "// from the hand bots in arvr/projects/superdex/assets/bots/hands. Do not edit: rerun the\n",
        "// script instead.\n",
        "//\n",
        "// Pruned BotPrefab JSON of the pose skeleton bots (SuperDexSkeletonBots.cpp).\n",
        "\n",
        "#pragma once\n",
        "\n",
        "// clang-format off\n",
    ]
    for skeleton, directory, stem in _SKELETONS:
        for side_cpp, side in _SIDES:
            parts.append("\n")
            parts.append(
                _to_cpp(
                    f"kSkeletonBotJson_{skeleton}_{side_cpp}",
                    _load_pruned(directory, stem, side),
                )
            )
    parts.append("// clang-format on\n")
    return "".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--check", action="store_true", help="exit with 1 if the output is out of date"
    )
    args = parser.parse_args(argv)
    text = generate()
    if args.check:
        current = _OUTPUT.read_text() if _OUTPUT.exists() else None
        if current != text:
            print(
                f"{_OUTPUT} is out of date; rerun {Path(__file__).name}",
                file=sys.stderr,
            )
            return 1
        return 0
    _OUTPUT.write_text(text)
    print(f"Wrote {_OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
